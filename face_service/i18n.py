"""Minimal, zero-dependency i18n for the tray, its windows, the wizard, the password dialog and the
lock-screen gesture prompts.

Stage 9 (act 9b R16):
* English and Russian are the product languages -- complete and key-for-key equal; the equality
  is pinned by tools/presence_guards_selftest.py.
* The ten other codes (ar de es fr hi ja ko pt vi zh) stay VALID in config.toml, so an old config
  loads, but they are not offered in any menu and show English. Their partial translations were
  removed: they carried stale meanings of changed texts (F-198) and unreviewed security wording.
* One glossary for users, no internal names (D-101, D-104, F-199): EN "Face Unlock service",
  "face profile", "sign-in screen", "face sign-in", "presence check", "absence", "lock the PC"
  versus "face sign-in pause" (the lockout after failed attempts). RU: «сервис Face Unlock»,
  «профиль лица», «экран входа», «вход по лицу», «проверка присутствия», «отсутствие»,
  «блокировка компьютера» versus «пауза входа по лицу». Russian texts address the user formally,
  the lock-screen prompts included (D-102).
* Counts are written as counters ("Shots: 12 / 15", «Снимков: 12 из 15»), which reads right for
  every number in both languages (F-201).
* The first-run language follows the Windows display language (GetUserDefaultUILanguage):
  Russian -> "ru", anything else -> "en" (F-169: locale.getlocale() never matched on Windows).

Usage::

    from face_service.i18n import t, set_language
    set_language("ru")
    label = t("settings.title")
    text = t("settings.editing", path="C:/x")
"""
