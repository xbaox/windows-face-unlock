TRANSLATIONS: dict[str, dict[str, str]] = {"en": _EN, "ru": _RU}

# ---------------------------------------------------------------------------
# Public API
# ---------------------------------------------------------------------------
_current_lang = DEFAULT_LANG
_lock = threading.Lock()

_LANG_RUSSIAN = 0x19              # PRIMARYLANGID of any Russian locale


def detect_system_language() -> str:
    """The Windows display language: Russian -> "ru", anything else -> "en" (F-169)."""
    try:
        import ctypes
        langid = int(ctypes.windll.kernel32.GetUserDefaultUILanguage())
        return "ru" if (langid & 0x3FF) == _LANG_RUSSIAN else DEFAULT_LANG
    except Exception:
        return DEFAULT_LANG


def set_language(lang: str) -> None:
    """Set the active language. Codes without a translation (valid or not) show English."""
    global _current_lang
    with _lock:
        _current_lang = lang if lang in TRANSLATIONS else DEFAULT_LANG


def get_language() -> str:
    return _current_lang


def t(key: str, **kwargs) -> str:
    """Translate ``key`` in the active language, formatting ``kwargs`` in. Falls back to English,
    then to the raw key (a missing key is visible, never a KeyError)."""
    with _lock:
        lang = _current_lang
    table = TRANSLATIONS.get(lang) or _EN
    s = table.get(key) or _EN.get(key, key)
    if kwargs:
        try:
            return s.format(**kwargs)
        except Exception:
            return s
    return s


def shown_languages() -> Iterable[tuple[str, str]]:
    """(code, native name) of the languages offered in the menus: English and Russian (R16)."""
    return [(c, n) for c, n in LANGUAGES if c in SHOWN_CODES]
